"""Offline detection eval: triggers + scorecard classifier on simulated scenarios. No network, no Gemini,
no database. Usage: uv run python scripts/eval_detection.py [--seeds 20] [--write]

Each scenario is generated by the real simulator (app/simulator/scenarios.py) and turned into attempt rows
through the shop's own offline result + PayPal code table (like scripts/eval_ai.py rows_for), on a
simulated clock. The detector is then run every DETECT_EVERY seconds of simulated time, as the worker does:
  - trigger recall: the scenario fired at least one trigger (benign ones should not, or only volume ones)
  - time to detect: simulated seconds from the first attempt to the first trigger
  - first verdict: the scorecard at the first trigger (what policy R0/R4 act on at once)
  - final verdict: the scorecard when the traffic ends (after the re-assessments)
  - false-positive triggers: fraud-tier triggers on benign scenarios

Everything here is SIMULATED traffic, and the scorecard's weights were tuned on this same simulator: the
numbers say the rules are consistent with our own model of attacks, not that they catch real ones.
"""

import heapq
import statistics
from collections import Counter
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from pathlib import Path

import typer

from app.detection.classifier import CLASSES, classify
from app.detection.features import AttemptRow, Baseline, card_key, compute_all
from app.detection.triggers import FRAUD_TRIGGERS, evaluate
from app.shop.catalog import CHEAPEST_SKU, PRODUCTS
from app.shop.service import classify as classify_result
from app.shop.service import email_domain, fingerprint, offline_result
from app.simulator.runner import to_request
from app.simulator.scenarios import BROWSER_UA, COMMON_DOMAINS, SCENARIOS, SimAttempt, customer_pool
from app.simulator.seed import HOURLY_WEIGHTS

DETECT_EVERY = timedelta(seconds=5)  # app/config.py detect_interval_s
TAIL = timedelta(minutes=2)  # keep ticking this long after the last attempt
START = datetime(2026, 10, 20, 19, 0, tzinfo=UTC)  # an evening hour: the shop's busiest
DOC = Path(__file__).resolve().parents[2] / "docs" / "eval-detection.md"
LABELS = (*CLASSES, "unclear", "-")  # "-": no trigger, so nothing was classified


@dataclass(frozen=True)
class Case:
    name: str
    parts: tuple[str, ...]  # simulator scenarios, interleaved on one clock
    expected: frozenset[str]  # acceptable classifications
    benign: bool
    sale_window: bool = False
    should_trigger: bool = True
    counts: tuple[int | None, ...] = ()  # per part; None = the scenario's default
    variant: str | None = None  # VARIANTS: a hard-case twist on the generated traffic
    cold_start: bool = False  # the shop has two days of history and no returning customers yet
    fumbler: bool = False  # one honest shopper fumbling: two wrong security codes, then other cards


CASES: tuple[Case, ...] = (
    Case("card_testing", ("card_testing",), frozenset({"card_testing"}), benign=False),
    Case("account_testing", ("account_testing",), frozenset({"account_testing"}), benign=False),
    Case("slow_drip", ("slow_drip",), frozenset({"card_testing"}), benign=False),
    Case("flash_sale", ("flash_sale",), frozenset({"genuine_rush"}), benign=True, sale_window=True),
    # A viral, unannounced rush: first-time shoppers (none in the shop's history), varied baskets.
    Case(
        "flash_sale_unannounced",
        ("flash_sale",),
        frozenset({"genuine_rush"}),
        benign=True,
        variant="new_shoppers",
    ),
    Case("paypal_outage", ("paypal_outage",), frozenset({"paypal_outage"}), benign=True),
    Case("normal_night", ("normal_night",), frozenset({"genuine_rush"}), benign=True, should_trigger=False),
    # Forty shoppers in a few minutes is far above an 8-orders-a-day shop's normal: volume triggers are right
    # to fire. What must not happen is a fraud-tier trigger or an attack verdict.
    Case("mixed_traffic", ("mixed_traffic",), frozenset({"genuine_rush"}), benign=True),
    Case(
        "attack_during_sale",
        ("flash_sale", "card_testing"),
        frozenset({"card_testing"}),
        benign=False,
        sale_window=True,
        counts=(60, 60),
    ),
    Case("stealth_bot", ("stealth_bot",), frozenset({"card_testing"}), benign=False),
    # Hard cases: a rush that looks like card testing on the surface.
    Case(
        "cheap_item_rush",
        ("flash_sale",),
        frozenset({"genuine_rush"}),
        benign=True,
        variant="cheap_item_new_shoppers",
    ),
    Case("cold_start_rush", ("flash_sale",), frozenset({"genuine_rush"}), benign=True, cold_start=True),
    # The cheap-item rush plus one shopper who mistypes a security code twice and then tries two other
    # cards: one device must never turn a rush into an attack (or a refund).
    Case(
        "cheap_item_rush_fumbler",
        ("flash_sale",),
        frozenset({"genuine_rush", "unclear"}),
        benign=True,
        variant="cheap_item_new_shoppers",
        fumbler=True,
    ),
)


def _cheap_item_new_shoppers(a: SimAttempt, i: int) -> SimAttempt:
    """A viral post about the cheapest item: first-time shoppers, all on one SKU, banks saying yes."""
    a.sku = CHEAPEST_SKU
    a.device_id = f"viral-{i}"
    return a


def _new_shoppers(a: SimAttempt, i: int) -> SimAttempt:
    """Nobody in the rush has bought here before (a viral post, not the shop's own mailing list)."""
    a.device_id = f"newcomer-{i}"
    return a


VARIANTS = {"cheap_item_new_shoppers": _cheap_item_new_shoppers, "new_shoppers": _new_shoppers}


def fumbler_attempts() -> list[SimAttempt]:
    """One real shopper: wrong security code twice on one card (two expiry guesses), a second card refused
    by the bank, a third card that goes through. Starts 90 s into the rush."""
    plan = [
        ("4111110000001111", "2030-11", "CCREJECT-CVV_F", "decline"),
        ("4111110000001111", "2031-11", "CCREJECT-CVV_F", "decline"),
        ("4222220000002222", "2029-04", "CCREJECT-REFUSED", "decline"),
        ("4333330000003333", "2032-01", "Test Buyer", "approve"),
    ]
    return [
        SimAttempt(
            delay_s=90 if n == 0 else 25,
            sku=CHEAPEST_SKU,
            method="card",
            device_id="fumbling-shopper",
            user_agent=BROWSER_UA,
            email="fumbler@gmail.com",
            card_number=number,
            card_expiry=expiry,
            card_name=name,
            outcome=outcome,
        )
        for n, (number, expiry, name, outcome) in enumerate(plan)
    ]


def baseline(cold_start: bool = False) -> Baseline:
    """A month of the seeded candle shop: 8 orders a day, evening-heavy, ~3% honest declines. Cold start:
    two days of history and nobody has bought twice yet."""
    pool = customer_pool()
    total = sum(HOURLY_WEIGHTS)
    hourly = tuple(8 * w / total for w in HOURLY_WEIGHTS)
    if cold_start:
        return Baseline(attempts_per_hour_mean=8 / 24, decline_rate=0.03, history_days=2, hourly_rate=hourly)
    return Baseline(
        attempts_per_hour_mean=8 / 24,
        attempts_per_hour_std=0.6,
        decline_rate=0.03,
        error_rate=0.005,
        known_domains=frozenset(COMMON_DOMAINS),
        known_fingerprints=frozenset(fingerprint(d, BROWSER_UA) for d, _ in pool),
        history_days=28,
        hourly_rate=hourly,
    )


def _row(name: str, a: SimAttempt, ts: datetime) -> AttemptRow:
    req = to_request("eval", name, a, "offline")
    assert req.offline is not None
    c = classify_result(offline_result(req.offline, False, a.method, req.card), a.method)
    return AttemptRow(
        ts=ts,
        sku=a.sku,
        amount=float(PRODUCTS[a.sku].price),
        method=a.method,
        fingerprint_hash=fingerprint(a.device_id, a.user_agent),
        email_domain=email_domain(a.email),
        card_key=card_key(a.card_number[:6], a.card_number[-4:], a.card_expiry) if a.card_number else None,
        payer_id_hash=a.payer_id,
        outcome=c.outcome,
        decline_code=c.decline_code,
        decline_category=c.category,
    )


def rows_for(case: Case, seed: int, start: datetime = START) -> list[AttemptRow]:
    """The case's scenarios on one forward clock (parts run in parallel, each on its own delays)."""
    streams = []
    for i, part in enumerate(case.parts):
        count = case.counts[i] if i < len(case.counts) else None
        kwargs = {"seed": seed * 100 + i} | ({"count": count} if count else {})
        attempts = list(SCENARIOS[part]("offline", **kwargs))
        if case.variant:
            attempts = [VARIANTS[case.variant](a, n) for n, a in enumerate(attempts)]
        streams.append((part, attempts))
    if case.fumbler:
        streams.append(("fumbler", fumbler_attempts()))
    timed: list[tuple[datetime, int, str, SimAttempt]] = []
    for i, (part, attempts) in enumerate(streams):
        t = start
        for a in attempts:
            t += timedelta(seconds=a.delay_s)
            timed.append((t, i, part, a))
    return [_row(part, a, ts) for ts, _, part, a in heapq.nsmallest(len(timed), timed, key=lambda x: x[:2])]


@dataclass
class RunResult:
    triggered: bool = False
    fraud_triggered: bool = False
    detect_s: float | None = None
    triggers: set[str] = field(default_factory=set)
    first: str = "-"
    first_conf: float = 0.0
    final: str = "-"


def run(case: Case, seed: int, base: Baseline) -> RunResult:
    rows = rows_for(case, seed)
    first_ts, last_ts = rows[0].ts, rows[-1].ts
    out = RunResult()
    now = first_ts
    while now <= last_ts + TAIL:
        feats = compute_all(rows, now, base)
        fired = evaluate(feats, base)
        if fired:
            out.triggers |= set(fired)
            if not out.triggered:
                out.triggered = True
                out.detect_s = (now - first_ts).total_seconds()
                verdict = classify(feats, base, sale_active=case.sale_window)
                out.first, out.first_conf = verdict.classification, verdict.confidence
        if now >= last_ts and out.triggered and out.final == "-":
            out.final = classify(feats, base, sale_active=case.sale_window).classification
        now += DETECT_EVERY
    out.fraud_triggered = bool(out.triggers & FRAUD_TRIGGERS)
    return out


@dataclass
class CaseSummary:
    case: Case
    runs: list[RunResult]

    @property
    def recall(self) -> float:
        return sum(r.triggered for r in self.runs) / len(self.runs)

    @property
    def fraud_rate(self) -> float:
        return sum(r.fraud_triggered for r in self.runs) / len(self.runs)

    @property
    def median_detect(self) -> float | None:
        times = [r.detect_s for r in self.runs if r.detect_s is not None]
        return statistics.median(times) if times else None

    def accuracy(self, attr: str) -> float | None:
        """Share of triggered runs whose verdict was expected; None when no run triggered."""
        judged = [getattr(r, attr) for r in self.runs if r.triggered]
        return sum(c in self.case.expected for c in judged) / len(judged) if judged else None

    def unclear(self, attr: str = "first") -> float:
        judged = [getattr(r, attr) for r in self.runs if r.triggered]
        return sum(c == "unclear" for c in judged) / len(judged) if judged else 0.0

    def attack_calls(self) -> int:
        """Runs whose first or final verdict was an attack class."""
        attacks = {"card_testing", "account_testing"}
        return sum(r.first in attacks or r.final in attacks for r in self.runs)


def evaluate_all(seeds: int, cases: tuple[Case, ...] = CASES) -> list[CaseSummary]:
    return [CaseSummary(c, [run(c, s + 1, baseline(c.cold_start)) for s in range(seeds)]) for c in cases]


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{x * 100:.0f}%"


def markdown(summaries: list[CaseSummary], seeds: int) -> str:
    lines = [
        "| Scenario | Benign | Trigger recall | Fraud-tier triggers | Median time to detect | "
        "First verdict correct | Final verdict correct | Unclear (first) | Triggers seen |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in summaries:
        detect = f"{s.median_detect:.0f} s" if s.median_detect is not None else "-"
        seen = Counter(t for r in s.runs for t in r.triggers)
        triggers = ", ".join(f"{t} ({n})" for t, n in sorted(seen.items(), key=lambda x: (-x[1], x[0])))
        lines.append(
            f"| {s.case.name} | {'yes' if s.case.benign else 'no'} | {_pct(s.recall)} | {_pct(s.fraud_rate)} "
            f"| {detect} | {_pct(s.accuracy('first'))} | {_pct(s.accuracy('final'))} | "
            f"{_pct(s.unclear())} | {triggers or '-'} |"
        )
    out = [f"Seeds per scenario: {seeds}. Verdict accuracy counts only runs that triggered.", "", *lines, ""]
    for attr, title in (("first", "First verdict"), ("final", "Final verdict")):
        out += [
            f"**Confusion matrix, {title.lower()}** (rows: scenario, columns: scorecard classification; "
            "`-` = never triggered)",
            "",
            "| Scenario | " + " | ".join(LABELS) + " |",
            "|---|" + "---|" * len(LABELS),
        ]
        for s in summaries:
            counts = Counter(getattr(r, attr) for r in s.runs)
            out.append(
                f"| {s.case.name} | " + " | ".join(str(counts.get(label, 0)) for label in LABELS) + " |"
            )
        out.append("")
    return "\n".join(out)


LIMITS = """## What this does not show, and what still fails

- **Tuned on our own simulator.** Trigger thresholds and scorecard weights were adjusted until these
  scenarios behaved; a real attacker who does not look like our simulator can beat them. We have no real
  attack sessions to test on (public fraud datasets are single transactions, not sessions).
- **The simulator was changed in this phase too:** the real-shopper scenarios (flash sale, outage, normal
  night) used evenly spread random gaps, which made them look machine-regular to the new timing feature.
  Real independent shoppers arrive as a Poisson process, so they now use exponential gaps. account_testing
  now leaves most wallet orders unapproved (CREATED), as stolen logins mostly fail PayPal's own checks.
  Honest refusals were all "insufficient funds" (which the scorecard reads as bad luck); they are now
  mostly the bank's generic refusal, which is what real honest traffic mostly shows.
- **Honest refusals.** The benign scenarios refuse about 7% of payments (mixed_traffic: the first card of
  about one shopper in eight), 60% of them with the bank's generic "do not honor" and the rest insufficient
  funds. Generic refusals are never a core card-testing signal, and stolen-card or guessing refusals count
  only when they come from several devices; with that, no benign run here is called an attack. Real shops
  see other mixes (and honest wrong-security-code typos), which this simulator does not model beyond the
  one fumbling shopper.
- **flash_sale** draws 70% of its shoppers from the customers in the shop's history, which supports
  "genuine rush"; **flash_sale_unannounced** and **cheap_item_rush** are first-time shoppers only.
- **cheap_item_rush** (first-time shoppers all buying the cheapest item) is the hardest benign case: some
  verdicts are "unclear" (Gemini is then asked for a second opinion; R3 adds only 3-D Secure). It never
  fires a fraud-tier trigger and is never called an attack in this eval. **cheap_item_rush_fumbler** adds
  one shopper who mistypes a security code twice and tries two more cards: still never an attack, so
  that shopper is never blocked or refunded on the scorecard's say-so.
- **Early verdicts on a mixed attack** can be wrong: in attack_during_sale the first verdict is sometimes
  "genuine rush", before stolen-card refusals have come from two devices. The re-assessments correct it,
  and during an announced sale policy R4 is 3-D Secure only anyway.
- **stealth_bot** (a new device every attempt, one try every 1-5 minutes) is caught only by the CUSUM
  slow_declines trigger, after about 25 minutes. A slow bot whose cards are mostly accepted, or whose
  refusals are all "insufficient funds" or the generic "do not honor", would not be caught by it.
- **Busy shops:** the CUSUM's reference grows with the shop's normal decline traffic (capped so it can
  still grow). Outside this eval, a shop at about 300 attempts an hour with 10% declines caught a bot
  refusing every 2 minutes in about 20 minutes, and did not catch one refusing every 3 minutes within
  the hour.
- **account_testing** is called at once only because the simulated bots reuse a few devices (several PayPal
  accounts per device). A device-rotating account tester would be recognised only once its wallet orders
  are two minutes old and still unapproved; that variant is not in this eval.
- The first verdict on an outage needs at least three processor errors; before that it can be "unclear".
  Errors any client can cause on purpose (capturing an order nobody approved, ORDER_NOT_APPROVED and
  similar) are not counted as errors at all, and an outage verdict never relaxes the defences while
  fraud-tier triggers fired in the same incident. That attack is not a scenario here; it is covered by
  unit tests.
"""


def write_doc(table: str) -> None:
    DOC.write_text(
        "# Detection eval (offline, simulated)\n\n"
        "Generated by `cd backend && uv run python scripts/eval_detection.py --write`. No network, "
        "no Gemini, no database: each scenario is produced by the real simulator, turned into attempt "
        "rows through the shop's own offline result and PayPal code table, and replayed on a simulated "
        "clock with the detector running every 5 simulated seconds (as the worker does).\n\n"
        "**Honesty note:** all traffic here is SIMULATED, and the scorecard weights and trigger thresholds "
        "were tuned on this same simulator. These numbers show the rules are consistent with our model of "
        "attacks, rushes and outages; they are not a measurement on real attacks, which we do not have.\n\n"
        "- *Trigger recall*: share of runs that fired any trigger (benign scenarios may fire volume-tier "
        "ones: a sale is busy).\n"
        "- *Fraud-tier triggers*: share of runs that fired one (decline_spike, fraud_declines, "
        "cheap_sku_card_cycling, slow_declines). On a benign scenario that is a false positive: policy R0 "
        "would switch on 3-D Secure.\n"
        "- *First verdict*: the scorecard at the first trigger. *Final verdict*: when the traffic ends.\n\n"
        f"{table}\n{LIMITS}"
    )


def main(
    seeds: int = typer.Option(20, help="Seeds per scenario"),
    write: bool = typer.Option(False, help=f"Also write {DOC.name}"),
) -> None:
    summaries = evaluate_all(seeds)
    table = markdown(summaries, seeds)
    print(table)
    if write:
        write_doc(table)
        print(f"wrote {DOC}")


if __name__ == "__main__":
    typer.run(main)
